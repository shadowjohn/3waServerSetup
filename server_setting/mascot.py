ASCII = "  +---------------+\n  |      3wa      |\n  +---------------+\n\n   Server Setup"


def ascii_fallback(requested=False):
    encoding = (getattr(sys.stdout, 'encoding', None) or 'ascii').lower().replace('-', '')
    return requested or 'NO_COLOR' in os.environ or encoding in {'ascii', 'usascii'}


def render_mascot(ascii_mode=False):
    if ascii_mode:
        return Text(ASCII)
    result = Text(no_wrap=True, overflow='crop')
    style = Style(color='#ffffff', bgcolor='#000000')
    # Unicode Braille dot numbers: left 1/2/3/7, right 4/5/6/8.
    weights = ((1, 8), (2, 16), (4, 32), (64, 128))
    for y in range(0, 80, 4):
        line = ''
        for x in range(0, 40, 2):
            mask = sum(weights[dy][dx] for dy in range(4) for dx in range(2)
                       if PIXELS[y + dy][x + dx] == '1')
            line += chr(0x2800 + mask)
        result.append(line, style)
        if y < 76:
            result.append('\n')
    return result
